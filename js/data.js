// Grid is row-major: grid[y][x]
function makeRoomGrid(w, h, { doors = [], windows = [] } = {}) {
  const grid = [];
  for (let y = 0; y < h; y++) {
    const row = [];
    for (let x = 0; x < w; x++) {
      let cell = TILE.FLOOR;
      if (y === 0 || x === 0) cell = TILE.WALL;
      row.push(cell);
    }
    grid.push(row);
  }
  for (const d of doors) grid[d.y][d.x] = TILE.DOOR;
  for (const win of windows) grid[win.y][win.x] = TILE.WINDOW;
  return grid;
}

