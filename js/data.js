// Grid is row-major: grid[y][x]
export function makeRoomGrid(w, h, { doors = [], windows = [], cutouts = [] } = {}) {
  const grid = [];
  for (let y = 0; y < h; y++) {
    const row = [];
    for (let x = 0; x < w; x++) {
      let cell = TILE.FLOOR;
      if (y === 0 || x === 0) cell = TILE.WALL;
      row.push(cell);
    }
    grid.push(row);
  }
  for (const c of cutouts) {
    for (let y = c.y0; y <= c.y1; y++) {
      for (let x = c.x0; x <= c.x1; x++) {
        if (y >= 0 && y < h && x >= 0 && x < w) grid[y][x] = TILE.VOID;
      }
    }
  }
  for (let y = 1; y < h; y++) {
    if (grid[y][1] === TILE.VOID) grid[y][0] = TILE.VOID;
  }
  for (let x = 1; x < w; x++) {
    if (grid[1] && grid[1][x] === TILE.VOID) grid[0][x] = TILE.VOID;
  }
  for (const d of doors) grid[d.y][d.x] = TILE.DOOR;
  for (const win of windows) grid[win.y][win.x] = TILE.WINDOW;
  return grid;
}

